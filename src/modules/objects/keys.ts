import type { ObjectsQuery } from "./types";

/**
 * Ключи Vue Query реестра. level/risk/q — клиентские проекции одного массива, и ключ,
 * зависящий от них, породил бы три копии одного снапшота и рассинхрон
 * «шапка графа ↔ список». `withRisk` — наоборот, серверный параметр: под ним живут
 * два снапшота (реестр/граф с риском и дашборд без него — свёртка риска бэку дорога).
 *
 * Риск больше не отдельный источник: он приехал вместе с объектами, поэтому отдельный
 * ключ под него не нужен — инвалидация `all` обновляет и топологию, и риск в обоих.
 */
export const objectsKeys = {
  all: ["objects"] as const,
  lists: () => [...objectsKeys.all, "list"] as const,
  list: (query: ObjectsQuery) => [...objectsKeys.lists(), query] as const,
};
